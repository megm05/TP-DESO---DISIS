-- Esquema de base de datos (PostgreSQL 16)
-- Corresponde al Diagrama Entidad-Relación final (documentacion/diagramas/der.puml)

-- EMPRESAS, PUESTOS Y COMPETENCIAS
CREATE TABLE Empresa (
    id_empresa      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE Puesto (
    id_puesto       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa      INTEGER NOT NULL REFERENCES Empresa (id_empresa),
    nombre          VARCHAR(100) NOT NULL,
    descripcion     VARCHAR(500)
);

CREATE TABLE Competencia (
    id_competencia  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE,
    tipo            VARCHAR(20)  NOT NULL CHECK (tipo IN ('TECNICA', 'ACTITUDINAL'))
);

-- Clase asociación Caracteristicas_del_puesto: ponderación mínima requerida
CREATE TABLE Puesto_Competencia (
    id_puesto           INTEGER NOT NULL REFERENCES Puesto (id_puesto),
    id_competencia      INTEGER NOT NULL REFERENCES Competencia (id_competencia),
    ponderacion_minima  NUMERIC(5,2) NOT NULL CHECK (ponderacion_minima BETWEEN 0 AND 10),
    PRIMARY KEY (id_puesto, id_competencia)
);

CREATE TABLE Factor (
    id_factor       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_competencia  INTEGER NOT NULL REFERENCES Competencia (id_competencia),
    nombre          VARCHAR(100) NOT NULL,
    descripcion     VARCHAR(500)
);

-- OPCIONES DE RESPUESTA Y PREGUNTAS
CREATE TABLE Opcion_respuesta (
    id_opcion       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE,
    descripcion     VARCHAR(500)
);

CREATE TABLE Detalle_opcion (
    id_detalle      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_opcion       INTEGER NOT NULL REFERENCES Opcion_respuesta (id_opcion),
    orden           INTEGER NOT NULL,
    descripcion     VARCHAR(200) NOT NULL,
    UNIQUE (id_opcion, orden)
);

CREATE TABLE Pregunta (
    id_pregunta     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factor       INTEGER NOT NULL REFERENCES Factor (id_factor),
    id_opcion       INTEGER NOT NULL REFERENCES Opcion_respuesta (id_opcion),
    nombre          VARCHAR(100) NOT NULL,
    pregunta        VARCHAR(500) NOT NULL,
    descripcion     VARCHAR(500),
    activo          BOOLEAN NOT NULL DEFAULT TRUE
);

-- Ponderación de cada opción para una pregunta (suman 10 por pregunta)
CREATE TABLE Ponderacion_opcion (
    id_pregunta     INTEGER NOT NULL REFERENCES Pregunta (id_pregunta),
    id_detalle      INTEGER NOT NULL REFERENCES Detalle_opcion (id_detalle),
    ponderacion     NUMERIC(4,2) NOT NULL CHECK (ponderacion BETWEEN 0 AND 10),
    PRIMARY KEY (id_pregunta, id_detalle)
);

-- USUARIOS
CREATE TABLE Consultor (
    id_consultor    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario  VARCHAR(15)  NOT NULL UNIQUE,
    contrasenia     VARCHAR(64)  NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    apellido        VARCHAR(100) NOT NULL
);

CREATE TABLE Candidato (
    id_candidato    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_candidato   INTEGER NOT NULL UNIQUE,
    tipo_doc        VARCHAR(3)   NOT NULL CHECK (tipo_doc IN ('DNI', 'LE', 'LC', 'PP')),
    nro_doc         VARCHAR(20)  NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    apellido        VARCHAR(100) NOT NULL,
    email           VARCHAR(150),
    genero          CHAR(1),
    fecha_nac       DATE,
    escolaridad     VARCHAR(100),
    UNIQUE (tipo_doc, nro_doc)
);

-- EVALUACIONES Y CUESTIONARIOS
CREATE TABLE Evaluacion (
    id_evaluacion    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_puesto        INTEGER NOT NULL REFERENCES Puesto (id_puesto),
    id_consultor     INTEGER NOT NULL REFERENCES Consultor (id_consultor),
    fecha_generacion DATE NOT NULL,
    estado           VARCHAR(20) NOT NULL
);

-- El cuestionario resuelve el N:M entre Evaluacion y Candidato
CREATE TABLE Cuestionario (
    id_cuestionario     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion       INTEGER NOT NULL REFERENCES Evaluacion (id_evaluacion),
    id_candidato        INTEGER NOT NULL REFERENCES Candidato (id_candidato),
    clave               VARCHAR(8)  NOT NULL,
    estado              VARCHAR(20) NOT NULL
                        CHECK (estado IN ('ACTIVO', 'EN_PROCESO', 'COMPLETO', 'INCOMPLETO', 'SIN_CONTESTAR')),
    fecha_ini           TIMESTAMP,
    fecha_fin           TIMESTAMP,
    ultimo_ingreso      TIMESTAMP,
    fecha_cambio_estado TIMESTAMP,
    cant_accesos        INTEGER NOT NULL DEFAULT 0,
    tiempo_max          NUMERIC(8,2)
);

CREATE TABLE Bloque_pregunta (
    id_bloque       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuestionario INTEGER NOT NULL REFERENCES Cuestionario (id_cuestionario),
    numero          INTEGER NOT NULL,
    completado      BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (id_cuestionario, numero)
);

-- Se crean vacías al armar el cuestionario (id_detalle y fecha en NULL)
-- y se completan cuando el candidato responde.
CREATE TABLE Respuesta (
    id_respuesta    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bloque       INTEGER NOT NULL REFERENCES Bloque_pregunta (id_bloque),
    id_pregunta     INTEGER NOT NULL REFERENCES Pregunta (id_pregunta),
    id_candidato    INTEGER NOT NULL REFERENCES Candidato (id_candidato),
    id_detalle      INTEGER REFERENCES Detalle_opcion (id_detalle),
    orden           INTEGER NOT NULL,
    fecha           TIMESTAMP
);

-- Resultados del cálculo de puntaje (CU026, observación 3)
CREATE TABLE Resultado_competencia (
    id_cuestionario INTEGER NOT NULL REFERENCES Cuestionario (id_cuestionario),
    id_competencia  INTEGER NOT NULL REFERENCES Competencia (id_competencia),
    total           NUMERIC(5,2) NOT NULL,
    PRIMARY KEY (id_cuestionario, id_competencia)
);

CREATE TABLE Resultado_factor (
    id_cuestionario INTEGER NOT NULL REFERENCES Cuestionario (id_cuestionario),
    id_factor       INTEGER NOT NULL REFERENCES Factor (id_factor),
    total           NUMERIC(5,2) NOT NULL,
    PRIMARY KEY (id_cuestionario, id_factor)
);

-- CONFIGURACION
-- Repositorio de configuraciones del sistema (CU026: instrucciones y parámetros)
CREATE TABLE Parametro (
    clave           VARCHAR(50) PRIMARY KEY,
    valor           VARCHAR(2000) NOT NULL,
    descripcion     VARCHAR(255)
);

-- REPORTES
CREATE TABLE Orden_merito (
    id_orden_merito  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_puesto        INTEGER NOT NULL REFERENCES Puesto (id_puesto),
    id_consultor     INTEGER NOT NULL REFERENCES Consultor (id_consultor),
    fecha_generacion DATE NOT NULL
);

-- Evaluaciones incluidas en un orden de mérito (CU028 paso 6: una, varias o TODAS)
CREATE TABLE Orden_merito_Evaluacion (
    id_orden_merito INTEGER NOT NULL REFERENCES Orden_merito (id_orden_merito),
    id_evaluacion   INTEGER NOT NULL REFERENCES Evaluacion (id_evaluacion),
    PRIMARY KEY (id_orden_merito, id_evaluacion)
);

CREATE TABLE Renglon_Orden_merito (
    id_orden_merito  INTEGER NOT NULL REFERENCES Orden_merito (id_orden_merito),
    nro_renglon      INTEGER NOT NULL,
    id_candidato     INTEGER NOT NULL REFERENCES Candidato (id_candidato),
    id_cuestionario  INTEGER NOT NULL REFERENCES Cuestionario (id_cuestionario),
    posicion         INTEGER,
    puntaje_obtenido NUMERIC(5,2),
    PRIMARY KEY (id_orden_merito, nro_renglon)
);

-- CU027 (no implementado en esta entrega; forma parte del diseño)
CREATE TABLE Reporte_comparativo (
    id_reporte       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidato     INTEGER NOT NULL REFERENCES Candidato (id_candidato),
    id_puesto        INTEGER NOT NULL REFERENCES Puesto (id_puesto),
    id_consultor     INTEGER NOT NULL REFERENCES Consultor (id_consultor),
    fecha_generacion DATE NOT NULL
);

-- AUDITORIA
-- CU023: usuario, fecha y hora de la eliminación de una pregunta
CREATE TABLE Registro_pregunta (
    id_registro     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consultor    INTEGER NOT NULL REFERENCES Consultor (id_consultor),
    nombre_borrado  VARCHAR(100) NOT NULL,
    fecha_hora      TIMESTAMP NOT NULL
);

-- Registros de auditoría de los ABM no implementados en esta entrega (diseño)
CREATE TABLE Registro_factor (
    id_registro     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consultor    INTEGER NOT NULL REFERENCES Consultor (id_consultor),
    nombre_borrado  VARCHAR(100) NOT NULL,
    fecha_hora      TIMESTAMP NOT NULL
);

CREATE TABLE Registro_competencia (
    id_registro     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consultor    INTEGER NOT NULL REFERENCES Consultor (id_consultor),
    nombre_borrado  VARCHAR(100) NOT NULL,
    fecha_hora      TIMESTAMP NOT NULL
);

CREATE TABLE Registro_puesto (
    id_registro     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consultor    INTEGER NOT NULL REFERENCES Consultor (id_consultor),
    nombre_borrado  VARCHAR(100) NOT NULL,
    fecha_hora      TIMESTAMP NOT NULL
);

CREATE TABLE Registro_opcion_respuesta (
    id_registro     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consultor    INTEGER NOT NULL REFERENCES Consultor (id_consultor),
    nombre_borrado  VARCHAR(100) NOT NULL,
    fecha_hora      TIMESTAMP NOT NULL
);

-- CU032 (no implementado en esta entrega): registro de cada corrida del proceso
CREATE TABLE Registro_ejecucion (
    id_ejecucion    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora      TIMESTAMP NOT NULL,
    accion          VARCHAR(15) NOT NULL CHECK (accion IN ('INICIO', 'FINALIZACION'))
);

-- INDICES
CREATE INDEX idx_pregunta_factor        ON Pregunta (id_factor);
CREATE INDEX idx_factor_competencia     ON Factor (id_competencia);
CREATE INDEX idx_cuestionario_candidato ON Cuestionario (id_candidato);
CREATE INDEX idx_cuestionario_evaluacion ON Cuestionario (id_evaluacion);
CREATE INDEX idx_bloque_cuestionario    ON Bloque_pregunta (id_cuestionario);
CREATE INDEX idx_respuesta_bloque       ON Respuesta (id_bloque);
CREATE INDEX idx_evaluacion_puesto      ON Evaluacion (id_puesto);
